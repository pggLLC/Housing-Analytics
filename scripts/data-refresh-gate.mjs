#!/usr/bin/env node
// scripts/data-refresh-gate.mjs — run the site's own checks on a freshly
// fetched data file before a scheduled job saves it.
//
//   node scripts/data-refresh-gate.mjs data/fred-data.json
//
// Finds every test under test/ that reads the file (by its path), minus the
// SKIP list below, and runs each with node. If any fails, the file is put back
// to its committed version (git checkout HEAD -- <file>) so yesterday's data
// stays live, and the script exits 1 so the job stops before its commit step
// and the workflow monitor opens an issue.
//
// Why: on 2026-11-11 the FRED refresh added October 2026 CPI. October 2025 was
// never published, the Economy page showed a 13-month change as year-over-year,
// and test/econ-dash-accuracy.test.js only caught it after the file was live,
// because data commits skip CI.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

// Tests that mention a data file but must not gate its refresh.
export const SKIP = {
  'test/inventory-mtime-sync.test.js': 'the commit step reconciles the inventory after the gate',
  'test/paper-typed-facts.test.mjs': 'paper figures are regenerated by a later job',
  'test/smoke.test.js': 'site-wide smoke check, not a check on this file',
  'test/public-config-no-secrets.test.js': 'scans config for secrets, not data values',
  'test/data-refresh-gate.test.mjs': 'tests this gate itself',
};

export function findChecks(root, dataFile) {
  const dir = path.join(root, 'test');
  const rel = dataFile.replace(/^\.\//, '');
  const base = path.basename(rel);
  return fs.readdirSync(dir)
    .filter((f) => /\.test\.(m?js)$/.test(f))
    .map((f) => 'test/' + f)
    .filter((f) => !SKIP[f])
    .filter((f) => {
      const src = fs.readFileSync(path.join(root, f), 'utf8');
      return src.includes(rel) || src.includes("'" + base + "'") || src.includes('"' + base + '"');
    })
    .sort();
}

export function runGate(root, dataFile, { log = console.log } = {}) {
  const checks = findChecks(root, dataFile);
  if (checks.length === 0) {
    log(`::error::No checks read ${dataFile}; refusing to pass an empty gate.`);
    return 1;
  }
  const failed = [];
  for (const f of checks) {
    const r = spawnSync(process.execPath, [f], { cwd: root, encoding: 'utf8' });
    if (r.status === 0) {
      log(`  pass  ${f}`);
    } else {
      failed.push(f);
      log(`  FAIL  ${f}\n${(r.stdout + r.stderr).trim().split('\n').slice(-12).join('\n')}`);
    }
  }
  if (failed.length === 0) {
    log(`Gate passed: ${checks.length} checks accept the new ${dataFile}.`);
    return 0;
  }
  const back = spawnSync('git', ['checkout', 'HEAD', '--', dataFile], { cwd: root, encoding: 'utf8' });
  log(`::error::${failed.length} of ${checks.length} checks fail on the new ${dataFile}: ${failed.join(', ')}. ` +
    (back.status === 0 ? 'Kept the committed version; nothing new is saved.' : 'Could not restore the committed version: ' + back.stderr.trim()));
  return 1;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dataFile = process.argv[2];
  if (!dataFile) {
    console.error('usage: node scripts/data-refresh-gate.mjs <data file>');
    process.exit(2);
  }
  process.exit(runGate(process.cwd(), dataFile));
}
